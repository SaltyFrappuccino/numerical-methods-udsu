# -*- coding: utf-8 -*-
"""
ЛР3, задание №8, вариант 11. МЕТОД НАИМЕНЬШИХ КВАДРАТОВ (МНК).

КОРОТКАЯ ШПАРГАЛКА ДЛЯ ЗАЩИТЫ
1. Даны семь точек (x_i, y_i). Нужно найти наиболее подходящую ПРЯМУЮ.
2. По заданию ищем Q1(x) = a0 + a1*x. a0 — пересечение с осью Y,
   a1 — наклон (как b и k в школьной формуле y = k*x + b).
3. МНК минимизирует S = сумма (Q1(x_i) - y_i)^2 — формула (36) учебника.
4. По формуле (37) считаем S0, S1, S2, t0, t1 и получаем систему:
       S0*a0 + S1*a1 = t0
       S1*a0 + S2*a1 = t1
5. Исключаем a0 из системы, находим a1, затем a0.
6. Подставляем коэффициенты в прямую, считаем S и проверяем оба
   нормальных уравнения. S — НЕ верхняя оценка ошибки коэффициентов.

Ниже собраны реальные функции из нашего src/least_squares.py и
действия из src/main.py. Добавлены только учебные комментарии.
"""

# Исходные данные из нашего src/data.py.
# xs[i] и ys[i] вместе задают одну исходную точку.
XS = [0, 1, 2, 3, 4, 5, 6]
YS = [-3.31, -3.53, -3.25, -3.19, -3.11, -3.24, -3.38]


def fit_line(xs, ys):
    """Находит коэффициенты Q₁(x) = a₀ + a₁x методом наименьших квадратов."""

    # Каждому X должен соответствовать Y; для прямой нужны хотя бы две точки.
    if len(xs) != len(ys) or len(xs) < 2:
        raise ValueError("Нужно как минимум две пары координат x и y")

    # ПЯТЬ СУММ из §4.5 учебника (обозначения перед формулой (37)).
    S0 = len(xs)                           # Число точек: 7.
    S1 = sum(xs)                           # Сумма X: 0 + 1 + ... + 6 = 21.
    S2 = sum(x**2 for x in xs)             # Сумма квадратов X: 91.
    t0 = sum(ys)                           # Сумма Y: -23.01.
    t1 = sum(xs[i] * ys[i] for i in range(S0))  # Сумма x_i*y_i: -68.52.

    # Теперь по формуле (37) получили НОРМАЛЬНУЮ СИСТЕМУ:
    # 7*a0 + 21*a1 = -23.01
    # 21*a0 + 91*a1 = -68.52
    # Это система двух уравнений с двумя неизвестными a0 и a1.

    # Множитель исключения a0: первое уравнение умножаем на 21/7 = 3.
    factor = S1 / S0

    # Вычитаем из второго уравнения первое, умноженное на factor.
    # При a0 получится ноль, останется: left*a1 = right.
    left = S2 - factor * S1     # 91 - 3*21 = 28.
    right = t1 - factor * t0    # -68.52 - 3*(-23.01) = 0.51.

    # Нельзя делить на ноль: если все x одинаковые, наклон неоднозначен.
    # Порог 1e-12 — защита в нашей программе, а не формула МНК.
    if abs(left) < 1e-12:
        raise ValueError("Коэффициенты прямой нельзя определить: недостаточно разных x")

    # Решаем уравнение 28*a1 = 0.51: это наклон прямой.
    a1 = right / left

    # Подставляем a1 в первое нормальное уравнение и находим a0.
    a0 = (t0 - S1 * a1) / S0

    # Возвращаем коэффициенты и пять сумм для печати и проверки.
    return a0, a1, (S0, S1, S2, t0, t1)


def line_value(x, a0, a1):
    """Вычисляет значение найденной прямой при заданном x."""
    # Q1(x) — расчётная высота нашей прямой, не исходное табличное y.
    return a0 + a1 * x


def squared_error(xs, ys, a0, a1):
    """Вычисляет сумму квадратов отклонений прямой от табличных точек."""
    S = 0.0                       # Сначала сумма квадратов равна нулю.

    for i in range(len(xs)):     # Перебираем все семь исходных точек.
        Q = line_value(xs[i], a0, a1)  # Высота прямой в x_i.
        difference = Q - ys[i]        # Разница с табличной высотой y_i.
        S += difference**2            # Квадрат разницы прибавляем к S.

    return S                     # Формула (36) учебника: S = сумма квадратов.


def main():
    """Строит прямую МНК для варианта 11 и проверяет результат."""
    # Здесь реально вызываем функцию МНК, которая ищет a0 и a1.
    a0, a1, sums = fit_line(XS, YS)
    S0, S1, S2, t0, t1 = sums   # Получаем обратно пять рассчитанных сумм.

    print("ЛР №3, задание №8, вариант 11")
    print("Метод наименьших квадратов")
    print()
    print(f"S0 = {S0}")
    print(f"S1 = {S1}")
    print(f"S2 = {S2}")
    print(f"t0 = {t0:.6f}")
    print(f"t1 = {t1:.6f}")
    print()
    print("Нормальная система:")
    print(f"{S0}*a0 + {S1}*a1 = {t0:.6f}")
    print(f"{S1}*a0 + {S2}*a1 = {t1:.6f}")
    print()
    print(f"a0 = {a0:.9f}")
    print(f"a1 = {a1:.9f}")
    print(f"Q1(x) = {a0:.9f} + ({a1:.9f})*x")
    print()
    print(" x       y          Q1(x)       Q1(x)-y     (Q1(x)-y)^2")

    # Выводим значения прямой и отклонения для каждой точки.
    for i in range(len(XS)):
        x = XS[i]
        y = YS[i]
        Q = line_value(x, a0, a1)
        difference = Q - y
        print(f"{x:2}  {y:9.5f}  {Q:12.8f}  {difference:12.8f}  {difference**2:14.9f}")

    # Оцениваем, насколько хорошо прямая приблизила точки.
    S = squared_error(XS, YS, a0, a1)
    print()
    print(f"Сумма квадратов отклонений: S = {S:.9f}")

    # Проверяем нормальную систему ПОДСТАНОВКОЙ найденных a0 и a1.
    # Левая часть минус правая должна быть близка к нулю.
    first = S0 * a0 + S1 * a1 - t0
    second = S1 * a0 + S2 * a1 - t1

    # Небольшую погрешность округлений (до 1e-10) разрешаем.
    if abs(first) > 1e-10 or abs(second) > 1e-10:
        raise ArithmeticError("Проверка нормальной системы не пройдена")

    print("Проверка нормальной системы пройдена")


if __name__ == "__main__":
    # Запуск этого файла сразу выполняет весь разбор ЛР3 №8.
    main()
